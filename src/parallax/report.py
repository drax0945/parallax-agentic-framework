def _render_structures(molecules: Sequence[dict[str, str]]) -> str:
    if not molecules:
        return ""
    from .chem.structure import svg

    cards = []
    for entry in molecules:
        smiles = (entry or {}).get("smiles", "")
        if not smiles:
            continue
        caption = entry.get("caption", "")
        try:
            drawing = svg(smiles, width=300, height=240)
            drawing = re.sub(r"<\?xml[^>]*\?>", "", drawing).strip()
        except Exception:
            drawing = f"<p class='caption'>could not render: {html.escape(smiles)}</p>"
        cards.append(
            "<div class='card'>"
            + drawing
            + (f"<div class='caption'>{html.escape(caption)}</div>" if caption else "")
            + f"<div class='smiles'>{html.escape(smiles)}</div>"
            + "</div>"
        )
    if not cards:
        return ""
    return "<section class='structures'>" + "".join(cards) + "</section>"


def _render_references(include: bool) -> str:
    if not include:
        return ""
    citations = registry().all()
    if not citations:
        return (
            "<section class='refs'><h2>Sources</h2><p class='meta'>No sources were recorded "
            "for this report. That is itself a finding: nothing here is externally grounded.</p></section>"
        )
    items = []
    for citation in citations:
        badge = ""
        if citation.verified is True:
            badge = " <span class='badge'>DOI verified</span>"
        elif citation.verified is False:
            badge = " <span class='badge warn'>DOI did not resolve</span>"
        link = (
            f"<a href='https://doi.org/{citation.doi}'>https://doi.org/{citation.doi}</a>"
            if citation.doi
            else (f"<a href='{html.escape(citation.url)}'>{html.escape(citation.url)}</a>" if citation.url else "")
        )
        reference = html.escape(citation.reference().split(". https://")[0])
        items.append(
            f"<li><code>{html.escape(citation.key)}</code> — {reference}. {link}{badge}</li>"
        )
    return (
        "<section class='refs'><h2>Sources</h2><ul>" + "".join(items) + "</ul></section>"
    )


def render_report(
    *,
    title: str,
    markdown: str,
    molecules: Sequence[dict[str, str]] = (),
    filename: str | None = None,
    include_bibliography: bool = True,
) -> dict[str, Any]:
    cfg = settings()
    cfg.reports_dir.mkdir(parents=True, exist_ok=True)

    body = md.markdown(
        markdown,
        extensions=["tables", "fenced_code", "sane_lists", "toc", "attr_list"],
    )

    citations = registry().all()
    verified = [c for c in citations if c.verified is True]
    unverified = [c for c in citations if c.verified is False]
    verification = ""
    if verified or unverified:
        verification = f" · {len(verified)} DOIs verified"
        if unverified:
            verification += f", {len(unverified)} failed verification"

    document = TEMPLATE.format(
        title=html.escape(title),
        css=CSS,
        timestamp=utcnow(),
        n_citations=len(citations),
        verification=verification,
        structures=_render_structures(molecules),
        body=body,
        references=_render_references(include_bibliography),
    )

    stem = filename or re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")[:60] or "report"
    if not stem.endswith(".html"):
        stem += ".html"
    path = cfg.reports_dir / stem
    path.write_text(document, encoding="utf-8")

    # Keep the machine-readable sources next to the human report.
    registry().save(cfg.reports_dir / f"{Path(stem).stem}-sources")

    return {
        "path": str(path),
        "title": title,
        "n_citations": len(citations),
        "dois_verified": len(verified),
        "dois_failed_verification": [c.key for c in unverified],
        "bytes": path.stat().st_size,
        "sources_exported_to": str(cfg.reports_dir / f"{Path(stem).stem}-sources"),
        "note": "Open the HTML file directly; structures are embedded, nothing loads remotely.",
    }
